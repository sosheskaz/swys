// The fixture validity ends before any real run, so the wall-clock remaining
// time that NewCertInfo computes always renders as "expired", while chain
// verification is pinned inside the validity window.
var (
	fuzzCertificateTextNotBefore  = time.Date(2020, time.January, 1, 0, 0, 0, 0, time.UTC)
	fuzzCertificateTextNotAfter   = time.Date(2021, time.January, 1, 0, 0, 0, 0, time.UTC)
	fuzzCertificateTextVerifyTime = time.Date(2020, time.June, 1, 0, 0, 0, 0, time.UTC)
	fuzzCertificateTextRootKey    = ed25519.NewKeyFromSeed(bytes.Repeat([]byte{0x01}, ed25519.SeedSize))
	fuzzCertificateTextLeafKey    = ed25519.NewKeyFromSeed(bytes.Repeat([]byte{0x02}, ed25519.SeedSize))
)

// fuzzCertificateTextStyles removes exactly the SGR sequences textdisplay.Style
// emits for its roles, so rich output must reduce to the plain rendering.
var fuzzCertificateTextStyles = strings.NewReplacer(
	"\x1b[0m", "", "\x1b[1m", "", "\x1b[2m", "", "\x1b[31m", "", "\x1b[32m", "", "\x1b[33m", "",
)

const (
	fuzzCertificateTextSource       = "input"
	fuzzCertificateTextMismatchHost = "mismatch.invalid"
	fuzzCertificateTextExpiry       = " | expires 2021-01-01 (expired)"
)

type fuzzCertificateTextInput struct {
	subject      [3]string // CN, O, OU
	issuer       [3]string // CN, O, OU
	dnsNames     [2]string
	email        string
	uriPath      string
	mismatchHost bool
}

// FuzzCertificateText renders a verified leaf and root whose subject, issuer,
// and SAN fields carry generated bytes through both certificate text reports:
// the presentation report that cert commands write, in plain and rich styles,
// and the unstyled library report. Expected lines are re-derived from the
// parsed certificates rather than from CertInfo: every line must hold only
// printable runes (no C0, DEL, C1, or bidi controls), the report must keep the
// line structure of the certificate pair, printable names must appear
// verbatim, rich output may add only the renderer's SGR sequences, and the same
// report must render identically twice. A hostname mismatch carries the DNS
// names into the verification error as well.
func FuzzCertificateText(f *testing.F) {
	seeds := []fuzzCertificateTextInput{
		{
			subject:  [3]string{"leaf.example.test", "Example Org", "Web"},
			issuer:   [3]string{"Example Root CA", "Example", "PKI"},
			dnsNames: [2]string{"leaf.example.test", "www.example.test"},
			email:    "admin@example.test", uriPath: "/service",
		},
		{
			subject:  [3]string{`José, "Ops" <x>; +y\`, "世界", " leading"},
			issuer:   [3]string{"Root ✓", "", ""},
			dnsNames: [2]string{"*.example.test", ""},
		},
		{
			subject:  [3]string{"\x1b[2Jleaf", "\x1b]0;title\x07", "unit\x1b[31m"},
			issuer:   [3]string{"\x1b[2Jroot", "\x1b]8;;https://example.test\x1b\\", "\x1bc"},
			dnsNames: [2]string{"evil\x1b[2J.example.test", "\x1b]0;x\x07"},
			email:    "e\x1b[2J@example.test", uriPath: "/\x1b[2J", mismatchHost: true,
		},
		{
			subject:  [3]string{"\u009b2Jleaf", "\u202eevil", "\u2066isolate\u2069"},
			issuer:   [3]string{"\u009b31mroot", "\u200fmark", "del\x7f"},
			dnsNames: [2]string{"del\x7f.example.test", "nul\x00.example.test"},
		},
		{
			subject:      [3]string{"line\nbreak", "cr\r\nlf", "tab\tstop"},
			issuer:       [3]string{"root\nCA", "\r", "\v\f"},
			dnsNames:     [2]string{"inject\nline.example.test", "carriage\r.example.test"},
			mismatchHost: true,
		},
		{subject: [3]string{"", "Only Org", ""}, issuer: [3]string{"", "", ""}},
		{
			subject:  [3]string{"dev\u200d", "a\u200db", "\u200d"},
			issuer:   [3]string{"\u2028sep\u2029", "\u00a0nbsp", "\u00adsoft"},
			dnsNames: [2]string{"zwj.example.test", ""},
		},
		// x509 cannot encode invalid UTF-8 in a distinguished name or non-ASCII in
		// an IA5 SAN, so these inputs are skipped before rendering.
		{subject: [3]string{"\xff\xfe", "", ""}, issuer: [3]string{"root", "", ""}},
		{subject: [3]string{"leaf", "", ""}, issuer: [3]string{"root", "", ""}, dnsNames: [2]string{"caf\xc3\xa9.example.test", ""}},
	}
	for index := range seeds {
		seed := &seeds[index]
		f.Add(
			seed.subject[0], seed.subject[1], seed.subject[2],
			seed.issuer[0], seed.issuer[1], seed.issuer[2],
			seed.dnsNames[0], seed.dnsNames[1], seed.email, seed.uriPath, seed.mismatchHost,
		)
	}

	f.Fuzz(func(
		t *testing.T,
		subjectCN, subjectO, subjectOU, issuerCN, issuerO, issuerOU, dnsA, dnsB, email, uriPath string,
		mismatchHost bool,
	) {
		input := fuzzCertificateTextInput{
			subject:  [3]string{subjectCN, subjectO, subjectOU},
			issuer:   [3]string{issuerCN, issuerO, issuerOU},
			dnsNames: [2]string{dnsA, dnsB},
			email:    email, uriPath: uriPath, mismatchHost: mismatchHost,
		}
		if input.size() > maxFuzzFormatInputSize {
			t.Skip()
		}
		leaf, root, err := input.certificates()
		if err != nil {
			t.Skipf("x509 rejects the generated names: %v", err)
		}

		options := &x509.VerifyOptions{
			Roots:       x509.NewCertPool(),
			CurrentTime: fuzzCertificateTextVerifyTime,
			KeyUsages:   []x509.ExtKeyUsage{x509.ExtKeyUsageAny},
		}
		options.Roots.AddCert(root)
		if input.mismatchHost {
			options.DNSName = fuzzCertificateTextMismatchHost
		}
		report, err := InspectCertificates([]*x509.Certificate{leaf, root}, options, SelectFullChain, fuzzCertificateTextSource)
		require.NoError(t, err)
		verification := report.Verification
		require.NotNil(t, verification)
		if !input.mismatchHost {
			require.True(t, verification.Verified, "fixture chain must verify: %q", verification.Error)
		}
		if verification.Verified {
			require.Len(t, verification.Chains, 1, "fixture must verify through exactly one chain")
		} else {
			require.NotEmpty(t, verification.Error, "unverified report must carry its error")
		}

		names := []fuzzCertificateTextNames{fuzzCertificateTextExpected(leaf), fuzzCertificateTextExpected(root)}
		plain := renderFuzzCertificateText(t, &TextFormatter{Presentation: &textdisplay.Options{Width: 100}}, report)
		requireFuzzCertificateTextLines(t, plain, fuzzCertificatePresentationLines(names, verification), true)
		rich := renderFuzzCertificateText(t, &TextFormatter{Presentation: &textdisplay.Options{Width: 100, Rich: true}}, report)
		// Plain output holds no ESC, so equality after removing the renderer's own
		// sequences also proves rich output carries no other escape sequence.
		require.Equal(t, plain, fuzzCertificateTextStyles.Replace(rich), "rich output differs from plain beyond its styles")
		library := renderFuzzCertificateText(t, &TextFormatter{}, report)
		requireFuzzCertificateTextLines(t, library, fuzzCertificateLibraryLines(names, verification), false)
	})
}

func (input *fuzzCertificateTextInput) size() int {
	size := len(input.email) + len(input.uriPath)
	for _, value := range [...]string{
		input.subject[0], input.subject[1], input.subject[2],
		input.issuer[0], input.issuer[1], input.issuer[2],
		input.dnsNames[0], input.dnsNames[1],
	} {
		size += len(value)
	}
	return size
}

// certificates issues a CA named by the issuer fields and a leaf it signs.
// Ed25519 signatures are deterministic and both serials are fixed, so
// CreateCertificate draws nothing from the seeded reader.
func (input *fuzzCertificateTextInput) certificates() (*x509.Certificate, *x509.Certificate, error) {
	random := mathrand.NewChaCha8([32]byte{})
	rootTemplate := &x509.Certificate{
		SerialNumber:          big.NewInt(1),
		Subject:               fuzzCertificateTextName(input.issuer),
		NotBefore:             fuzzCertificateTextNotBefore,
		NotAfter:              fuzzCertificateTextNotAfter,
		KeyUsage:              x509.KeyUsageCertSign,
		BasicConstraintsValid: true,
		IsCA:                  true,
	}
	rootDER, err := x509.CreateCertificate(random, rootTemplate, rootTemplate, fuzzCertificateTextRootKey.Public(), fuzzCertificateTextRootKey)
	if err != nil {
		return nil, nil, fmt.Errorf("create root certificate: %w", err)
	}
	root, err := x509.ParseCertificate(rootDER)
	if err != nil {
		return nil, nil, fmt.Errorf("parse root certificate: %w", err)
	}

	leafTemplate := &x509.Certificate{
		SerialNumber: big.NewInt(2),
		Subject:      fuzzCertificateTextName(input.subject),
		NotBefore:    fuzzCertificateTextNotBefore,
		NotAfter:     fuzzCertificateTextNotAfter,
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	for _, name := range input.dnsNames {
		if name != "" {
			leafTemplate.DNSNames = append(leafTemplate.DNSNames, name)
		}
	}
	if input.email != "" {
		leafTemplate.EmailAddresses = []string{input.email}
	}
	if input.uriPath != "" {
		leafTemplate.URIs = []*url.URL{{Scheme: "https", Host: "uri.example.test", Path: input.uriPath}}
	}
	leafDER, err := x509.CreateCertificate(random, leafTemplate, root, fuzzCertificateTextLeafKey.Public(), fuzzCertificateTextRootKey)
	if err != nil {
		return nil, nil, fmt.Errorf("create leaf certificate: %w", err)
	}
	leaf, err := x509.ParseCertificate(leafDER)
	if err != nil {
		return nil, nil, fmt.Errorf("parse leaf certificate: %w", err)
	}
	return leaf, root, nil
}

func fuzzCertificateTextName(fields [3]string) pkix.Name {
	name := pkix.Name{CommonName: fields[0]}
	if fields[1] != "" {
		name.Organization = []string{fields[1]}
	}
	if fields[2] != "" {
		name.OrganizationalUnit = []string{fields[2]}
	}
	return name
}

type fuzzCertificateTextNames struct {
	commonName       string
	issuerCommonName string
	subject          string
	issuer           string
	dnsNames         string
}

// fuzzCertificateTextExpected derives each displayed name from the parsed
// certificate, falling back to the full distinguished name for an empty CN.
func fuzzCertificateTextExpected(cert *x509.Certificate) fuzzCertificateTextNames {
	names := fuzzCertificateTextNames{
		commonName:       cert.Subject.CommonName,
		issuerCommonName: cert.Issuer.CommonName,
		subject:          cert.Subject.String(),
		issuer:           cert.Issuer.String(),
		dnsNames:         "(none)",
	}
	if names.commonName == "" {
		names.commonName = names.subject
	}
	if names.issuerCommonName == "" {
		names.issuerCommonName = names.issuer
	}
	if len(cert.DNSNames) > 0 {
		names.dnsNames = strings.Join(cert.DNSNames, ", ")
	}
	return names
}

func renderFuzzCertificateText(t *testing.T, formatter *TextFormatter, report *CertificateReport) string {
	t.Helper()
	var first, second bytes.Buffer
	require.NoError(t, formatter.FormatReport(report, &first))
	require.NoError(t, formatter.FormatReport(report, &second))
	require.Equal(t, first.String(), second.String(), "the same report rendered differently")
	return first.String()
}

// fuzzCertificateTextLine describes one expected output line. A known value is
// the unescaped source text and must appear verbatim when it is printable.
type fuzzCertificateTextLine struct {
	prefix string
	value  string
	suffix string
	known  bool
}

func fuzzExactLine(text string) fuzzCertificateTextLine {
	return fuzzCertificateTextLine{prefix: text, known: true}
}

func fuzzValueLine(prefix, value string) fuzzCertificateTextLine {
	return fuzzCertificateTextLine{prefix: prefix, value: value, known: true}
}

// fuzzPresentationPrefixes aligns ASCII labels as one textdisplay field group.
func fuzzPresentationPrefixes(labels ...string) []string {
	width := 0
	for _, label := range labels {
		width = max(width, len(label))
	}
	prefixes := make([]string, len(labels))
	for index, label := range labels {
		prefixes[index] = "    " + label + strings.Repeat(" ", width-len(label)+2)
	}
	return prefixes
}

func fuzzCertificatePresentationLines(names []fuzzCertificateTextNames, verification *CertificateVerification) []fuzzCertificateTextLine {
	identity := fuzzPresentationPrefixes("Subject", "Issuer", "Serial", "Source", "DNS Names", "IPs")
	validity := fuzzPresentationPrefixes("Not Before", "Not After", "Remaining")
	key := fuzzPresentationPrefixes("Key", "Signature", "Usage", "Ext Usage", "CA", "SHA256", publicKeyFingerprintLabel)
	lines := []fuzzCertificateTextLine{fuzzExactLine("Certificates · " + SelectFullChain)}
	for index, cert := range names {
		lines = append(lines,
			fuzzExactLine(""),
			fuzzValueLine("  Certificate "+strconv.Itoa(index+1)+" · ", cert.commonName),
			fuzzValueLine(identity[0], cert.subject),
			fuzzValueLine(identity[1], cert.issuer),
			fuzzCertificateTextLine{prefix: identity[2]},
			fuzzValueLine(identity[3], fuzzCertificateTextSource),
			fuzzValueLine(identity[4], cert.dnsNames),
			fuzzValueLine(identity[5], "(none)"),
			fuzzExactLine(""),
			fuzzExactLine("  Validity"),
			fuzzCertificateTextLine{prefix: validity[0]},
			fuzzCertificateTextLine{prefix: validity[1]},
			fuzzValueLine(validity[2], "expired"),
			fuzzExactLine(""),
			fuzzExactLine("  Public Key and Usage"),
		)
		for _, prefix := range key {
			lines = append(lines, fuzzCertificateTextLine{prefix: prefix})
		}
	}
	lines = append(lines, fuzzExactLine(""), fuzzExactLine("  Certificate Verification · original leaf"))
	if verification.Verified {
		status := fuzzPresentationPrefixes("Status", "Chain 1")
		return append(lines,
			fuzzValueLine(status[0], "verified"),
			fuzzValueLine(status[1], names[0].commonName+" -> "+names[1].commonName),
		)
	}
	status := fuzzPresentationPrefixes("Status", "Error")
	return append(lines, fuzzValueLine(status[0], "not verified"), fuzzValueLine(status[1], verification.Error))
}

func fuzzLibraryPrefix(label string) string {
	return "  " + strings.Repeat(" ", max(0, 12-len(label))) + label + ": "
}

func fuzzCertificateLibraryLines(names []fuzzCertificateTextNames, verification *CertificateVerification) []fuzzCertificateTextLine {
	var lines []fuzzCertificateTextLine
	for index, cert := range names {
		if index > 0 {
			lines = append(lines, fuzzExactLine(""))
		}
		lines = append(lines,
			fuzzCertificateTextLine{value: cert.commonName + " | " + cert.issuerCommonName, suffix: fuzzCertificateTextExpiry, known: true},
			fuzzValueLine(fuzzLibraryPrefix("Subject"), cert.subject),
			fuzzValueLine(fuzzLibraryPrefix("Issuer"), cert.issuer),
			fuzzCertificateTextLine{prefix: fuzzLibraryPrefix("Serial")},
			fuzzValueLine(fuzzLibraryPrefix("DNS Names"), cert.dnsNames),
			fuzzValueLine(fuzzLibraryPrefix("IPs"), "(none)"),
			fuzzCertificateTextLine{prefix: fuzzLibraryPrefix("Not Before")},
			fuzzCertificateTextLine{prefix: fuzzLibraryPrefix("Not After")},
			fuzzCertificateTextLine{prefix: fuzzLibraryPrefix("Key")},
			fuzzCertificateTextLine{prefix: fuzzLibraryPrefix("Usage")},
		)
		if index == 0 {
			lines = append(lines, fuzzCertificateTextLine{prefix: fuzzLibraryPrefix("Ext Usage")})
		} else {
			lines = append(lines, fuzzValueLine(fuzzLibraryPrefix("CA"), "true"))
		}
		lines = append(lines,
			fuzzCertificateTextLine{prefix: fuzzLibraryPrefix("SHA256")},
			fuzzCertificateTextLine{prefix: fuzzLibraryPrefix(publicKeyFingerprintLabel)},
		)
	}
	if !verification.Verified {
		return append(lines, fuzzValueLine("certificate verification: not verified: ", verification.Error))
	}
	return append(lines,
		fuzzExactLine("certificate verification: verified"),
		fuzzExactLine("        Chains:"),
		fuzzValueLine("    [1] ", names[0].commonName+" -> "+names[1].commonName),
	)
}

// requireFuzzCertificateTextLines checks terminal safety before structure, so
// a smuggled control is reported as such rather than as a shifted line. Only
// the presentation renderer keeps U+200D, which joins emoji sequences.
func requireFuzzCertificateTextLines(t *testing.T, output string, want []fuzzCertificateTextLine, keepsZWJ bool) {
	t.Helper()
	require.True(t, utf8.ValidString(output), "output is not valid UTF-8: %q", output)
	body, terminated := strings.CutSuffix(output, "\n")
	require.True(t, terminated, "output does not end with a newline: %q", output)
	lines := strings.Split(body, "\n")
	for index, line := range lines {
		for _, char := range line {
			require.True(t, fuzzDisplayRune(char, keepsZWJ), "line %d holds non-printing rune %U: %q", index+1, char, line)
		}
	}
	require.Len(t, lines, len(want), "report line structure changed: %q", output)
	for index, line := range lines {
		expected := want[index]
		require.True(t, strings.HasPrefix(line, expected.prefix) && strings.HasSuffix(line, expected.suffix),
			"line %d = %q, want prefix %q and suffix %q", index+1, line, expected.prefix, expected.suffix)
		if expected.known && fuzzDisplayable(expected.value, keepsZWJ) {
			require.Equal(t, expected.prefix+expected.value+expected.suffix, line, "line %d did not keep its printable value verbatim", index+1)
		}
	}
}

// fuzzDisplayRune is the terminal-safe alphabet: unicode.IsPrint admits
// letters, marks, numbers, punctuation, symbols, and ASCII space, excluding
// every C0 and C1 control, DEL, and the bidi and other format controls.
func fuzzDisplayRune(char rune, keepsZWJ bool) bool {
	return unicode.IsPrint(char) || keepsZWJ && char == '\u200d'
}

func fuzzDisplayable(value string, keepsZWJ bool) bool {
	for _, char := range value {
		if !fuzzDisplayRune(char, keepsZWJ) {
			return false
		}
	}
	return utf8.ValidString(value)
}
